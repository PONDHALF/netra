assert len(PROVINCES) == 77

# ป้ายกรุงเทพฯ บางรุ่นพิมพ์ว่า "กรุงเทพ" หรือ "กรุงเทพฯ"
ALIASES: dict[str, str] = {
    "กรุงเทพ": "กรุงเทพมหานคร",
    "กรุงเทพฯ": "กรุงเทพมหานคร",
    "กทม": "กรุงเทพมหานคร",
    "อยุธยา": "พระนครศรีอยุธยา",
}

_CANDIDATES = PROVINCES + list(ALIASES)


def match_province(text: str, cutoff: float = 0.55) -> tuple[str | None, float]:
    """คืน (ชื่อจังหวัดที่ใกล้เคียงที่สุด, คะแนน 0-1) หรือ (None, 0) ถ้าไม่ใกล้พอ."""
    cleaned = "".join(ch for ch in text if "฀" <= ch <= "๿")
    if len(cleaned) < 2:
        return None, 0.0
    best, best_score = None, 0.0
    for cand in _CANDIDATES:
        score = difflib.SequenceMatcher(None, cleaned, cand).ratio()
        # ข้อความที่อ่านได้อาจเป็นแค่ส่วนหนึ่งของชื่อ (ป้ายโดนบัง)
        if len(cleaned) >= 3 and cleaned in cand:
            score = max(score, 0.6 + 0.4 * len(cleaned) / len(cand))
        if score > best_score:
            best, best_score = cand, score
    if best is None or best_score < cutoff:
        return None, 0.0
    return ALIASES.get(best, best), best_score
